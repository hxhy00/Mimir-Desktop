export function researchPaperDeaiContent(args: string): string {
  return withTarget(
    `对论文草稿做中英双语"去 AI 味"润色：让文字读起来像一位认真的人类研究者所写——不改变任何事实、数字、公式、方程或引用。这是措辞润色，不是内容修改。用户说 去AI味 / 去 AI / de-AI / humanize / 润色 时使用。
## 操作（逐节）
对 main.tex 每节（标题→摘要→引言→方法→实验→讨论→相关工作）：
1. **先遮蔽 LaTeX**：把绝不改动的东西先保护起来。公式（$...$、$$...$$、align 环境）换成 [MATH_1] 占位；\\cite/\\ref/\\label/\\eqref 及任何带编号的 \\command{...} 换成 [CITE_7]；整块的 table/figure/algorithm 环境各占一个 [TABLE_n]/[FIGURE_n]/[ALGO_n] 占位（内部 tabular/tikz/伪代码不重写，仅其中的 caption 可打磨）。占位符改写期间逐字节保持原样。
2. **判语言**：按段落主要脚本判中/英，用对应模式集。
3. **审计**：先逐条引用命中再改写。统计型模式需按段落或全篇计数。
4. **改写**：按优先级执行——换掉 AI 高频词/套话 → 重排句式（理论移出句首、合并重复开头、打破排比/整齐并列）→ 删段末总结与万能积极结尾 → 收紧模糊归因（无来源的"研究表明/专家认为"改写为本文自身分析，绝不编造引文）→ 平衡节奏（长短句交替，每段留一句 5–10 字短句）→ 必要时加入研究者判断/意外/局限等"人味"。
5. **复核**：重读整节两问——哪里还像 AI？这轮有没有增删任何事实/数字/引用/公式/结论？然后逐字节还原占位符，提示用户在「论文」模块编译——不平衡的 $$ 或断裂的 \\cite 由编译兜住，别用肉眼。
## 硬约束（命中即修）
| 项 | 阈值 |
| --- | --- |
| AI 高频词密度 | ≤2/段 |
| 段末总结套句 | ≤1/全文 |
| 整齐三元/排比 | ≤1/段 |
| 理论起笔段落占比 | ≤20% 段落 |
| 正文加粗 | ≤5/全文 |
| 泛化积极结尾 / 模糊归因 | 0 |
## 不要误报
完美语法与统一风格不是 AI 证明；单独一个学术词汇、一个 Moreover、一个孤立的破折号都算正常——要成堆出现才算信号。引文、标题、专名、被讨论中的短语逐字保留。`,
    'Research Paper-DeAI — 去 AI 味润色（中英）',
    args,
  )
}

