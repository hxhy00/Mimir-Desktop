const ADAPTED_NOTE =
  '（本技能改编自 Mimir 的 research-* 技能集；涉及本应用没有的工具处，均改为在「论文 / 图表 / 组会 / 实验」模块由用户执行，或要求用户粘贴内容后再继续。）'

function withTarget(sop: string, targetLabel: string, args: string): string {
  const argLine =
    args.trim() === ''
      ? `- 本次任务没有给出具体对象；若下方任何一步需要它，先向用户澄清再动手，不要自行编造。`
      : `- 本次任务对象：${args.trim()}`
  return `# ${targetLabel}\n\n${argLine}\n\n${sop}\n\n${ADAPTED_NOTE}`
}

