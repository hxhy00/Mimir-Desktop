export const IDEA_STEPS = `请按顺序完成一次文献锚定的科研「开题」梳理：
1. 先检查本空间 wiki 备忘（用 wiki_note 按需新建/追加，标题建议 idea:<课题>）；若已存在被标记为失败的同类方向，不要原样复活——在报告里说明重叠并转向真正的新点。
2. 用 arxiv_search 做 2–4 组聚焦检索，覆盖问题定义、方法族、最强基线；对每篇真正相关的论文调用 paper_fetch 存入文献库，notes 里写明它对本方向的价值；同时用 web_search 补 arXiv 之外的非学术来源。
3. 产出一份《想法报告》（直接作为本回复正文）：研究问题、最接近的已有工作（带 arXiv id）、你的假设与独特增量、主要风险。
4. 把假设与"为何不是重复失败方向"用 wiki_note 记一条备忘。
5. 收尾给用户：一句话假设、最近的工作、为什么这次值得做。`

export const PLAN_STEPS = `请按顺序完成一次「实验方案」梳理（基于既有讨论或新课题）：
1. 确认要规划的课题。若此前对话已产出《想法报告》则以它为准；否则先请用户给出课题名称与一句假设。
2. 产出结构化实验方案（作为本回复正文）：待验证假设清单；逐条假设对应的实验设计（名称、关键指标、能支撑/能否定它的结果）；按优先级排序并附算力提示（可在「服务器」模块查看可用 GPU）。
3. 用 wiki_note 保存方案备忘（标题建议 plan:<课题>），要点包括假设与判定规则。
4. 提醒用户：可在「实验」模块把方案录入为实验记录，跑完一个更新一个状态——失败的实验也记录，负证据同样算数。
5. 收尾给出：假设清单 + 检验每条假设的那个实验。`

export const PAPER_WRITE_STEPS = `请按顺序完成一次「论文写作」协助（面向本应用「论文」模块的 LaTeX 项目）：
1. 确认论文主题与现状。若参数或既有对话没有给出主题，先向用户确认要写的方向与目标期刊/会议风格。
2. 先列论文骨架（结构树：标题、摘要、引言、方法、实验、讨论/相关工作、结论；摘要在最后完整起草，但先留占位），随后逐节给出可直接粘贴到 main.tex 的内容。
3. 写作纪律：正文中的每个数字必须可回溯（实验记录/已查证来源），每个 \\cite{} 键在 references.bib 有对应条目（缺的提示用户从「文献库」导出 .bib 补齐）；图表只引用论文目录 figures/ 中真实存在的文件。
4. 写完全稿后，提示用户在「论文」模块编译并把错误/警告日志粘贴回来，你负责逐条修复直至通过。
5. 收尾给用户：标题、章节清单、编译状态与建议。`

export const PAPER_COMPILE_STEPS = `请把一次 LaTeX 编译输出解析为可执行诊断：
1. 若消息中还没有编译日志，请用户先在「论文」模块编译项目，再把「错误/警告/日志摘录」粘贴回来（可作为附件/文本随本消息一并给出）。
2. 收到日志后：按严重度排序给出诊断清单——每条含文件:行号、问题说明、修复建议（指出改哪一行、怎么改）。undefined reference/citation 要修；其余警告视重要程度上报。
3. 修复建议落地后，让用户再次编译并把结果贴回，直到错误清零；无错误但有警告时，给出按优先级排的警告清单。
4. 收尾给用户：是否已通过、剩余警告数量与建议。`

export const REVIEW_STEPS = `请扮演一位独立的同行评审者，对本次对象做一轮严肃评审：
1. 被评审内容必须以文本形式出现在本消息中（可直接粘贴正文/代码，或用附件给出）。若消息里没有可评审内容，先说明需要内容，而不是凭记忆评审。
2. 评审范围（scope）取自本次参数；没有指定时评审全部粘贴内容。
3. 输出：先给总评判定 PASS / WARN / FAIL，再给编号问题清单——每条注明位置（段落/行）、问题类型（论证、证据支撑、结构、表达、规范）、具体修改建议。
4. 判 FAIL 或 WARN 时，把最关键的前 N 条问题的修订要求交还给用户；用户修改后你可应要求复审。
5. 硬规则：只评审本消息实际给出的内容，绝不凭记忆补充材料；批评具体到可执行，表扬只针对真实存在的优点。`
